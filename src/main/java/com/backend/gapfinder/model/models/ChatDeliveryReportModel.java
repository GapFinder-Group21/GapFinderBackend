package com.backend.gapfinder.model.models;

import com.backend.gapfinder.model.enums.ChatDeliveryRouteEnum;

import jakarta.persistence.*;
import java.time.LocalDateTime;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.NoArgsConstructor;
import lombok.ToString;

// BQ 17 INDIVIDUAL TYPE 1: how long one chat message took from the tap on Send until the server saved it.
// The app measures it with the phone clock (the tap and the answer of the server are seen by the same clock),
// so the clocks of the phone and the server do not need to agree
@Entity
@Data
@EqualsAndHashCode(callSuper = true)
@NoArgsConstructor
@Table(
    name = "chat_delivery_reports",
    // One report per message: a report sent twice by the app queue is stored only once
    uniqueConstraints = @UniqueConstraint(columnNames = {"user_id", "client_id"}),
    indexes = @Index(name = "idx_chat_delivery_reports_tapped_at", columnList = "tapped_at")
)
public class ChatDeliveryReportModel extends BaseModel {

    // Student who sent the message
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    @ToString.Exclude
    @EqualsAndHashCode.Exclude
    private UserModel user;

    // Id generated by the app for the message (the same clientId of chat_messages)
    @Column(name = "client_id", nullable = false, length = 64)
    private String clientId;

    // Whether the message went out at once (DIRECT) or waited in the offline queue (QUEUED)
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private ChatDeliveryRouteEnum route;

    // Milliseconds from the tap on Send until the server answered that the message was saved
    @Column(name = "elapsed_ms", nullable = false)
    private Long elapsedMs;

    // Only QUEUED: milliseconds from the moment the connection came back until the server saved the message
    // (the part of the wait that depends on the app and not on the student being offline). Null if unknown
    @Column(name = "after_reconnect_ms")
    private Long afterReconnectMs;

    // When the student tapped Send, as the phone saw it (used to filter by period)
    @Column(name = "tapped_at", nullable = false)
    private LocalDateTime tappedAt;

    // When the server received the report
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // Sets the reception time before saving
    @PrePersist
    void onCreate() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
    }
}
