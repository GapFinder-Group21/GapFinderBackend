package com.backend.gapfinder.model.models;

import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.Data;
import lombok.EqualsAndHashCode;

// A chat message between two friends
@Entity
@Table(
    name = "chat_messages",
    // The same message sent twice (a retry from the app outbox) is stored only once
    uniqueConstraints = @UniqueConstraint(columnNames = {"sender_id", "client_id"}),
    indexes = @Index(name = "idx_chat_messages_pair", columnList = "sender_id, receiver_id, id")
)
@Data
@EqualsAndHashCode(callSuper = true)
public class ChatMessageModel extends BaseModel {

    // Max length of a message
    public static final int MAX_CONTENT_LENGTH = 500;

    // Student who sent the message
    @ManyToOne
    @JoinColumn(name = "sender_id", nullable = false)
    private UserModel sender;

    // Student who receives the message
    @ManyToOne
    @JoinColumn(name = "receiver_id", nullable = false)
    private UserModel receiver;

    // Text of the message
    @Column(nullable = false, length = MAX_CONTENT_LENGTH)
    private String content;

    // Id generated by the app (UUID) so a retried message is not duplicated
    @Column(name = "client_id", nullable = false, length = 64)
    private String clientId;

    // Date and time when the server stored the message
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;
}
