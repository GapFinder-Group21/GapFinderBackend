package com.backend.gapfinder.model.models;

import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.Data;
import lombok.EqualsAndHashCode;

// A period of time in which a student is studying: while it lasts the student is hidden from the matches
// and from the nearby friends. It is saved by time and by user, not as a flag on the gap, so it does not
// depend on the gap still existing (the weekly job can regenerate the gaps)
@Entity
@Table(
    name = "study_periods",
    // The same period sent twice (a retry from the app outbox) is stored only once
    uniqueConstraints = @UniqueConstraint(columnNames = {"user_id", "client_id"}),
    indexes = @Index(name = "idx_study_periods_user_end", columnList = "user_id, end_time")
)
@Data
@EqualsAndHashCode(callSuper = true)
public class StudyPeriodModel extends BaseModel {

    // A study period cannot last longer than this
    public static final int MAX_HOURS = 12;

    // Max length of the client id (a UUID has 36 characters)
    public static final int MAX_CLIENT_ID_LENGTH = 64;

    // Student who is studying
    @ManyToOne
    @JoinColumn(name = "user_id", nullable = false)
    private UserModel user;

    // Start of the study period
    @Column(name = "start_time", nullable = false)
    private LocalDateTime startTime;

    // End of the study period
    @Column(name = "end_time", nullable = false)
    private LocalDateTime endTime;

    // Gap the student chose to hide (informational only: it is not a foreign key, because the gaps can be
    // regenerated and the period must keep working by time)
    @Column(name = "gap_id")
    private Long gapId;

    // Id generated by the app (UUID) so a retried request is not duplicated
    @Column(name = "client_id", nullable = false, length = MAX_CLIENT_ID_LENGTH)
    private String clientId;

    // Date and time when the server stored the period
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;
}
